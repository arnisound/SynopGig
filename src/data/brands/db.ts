/** Touring amps (D80, D40, D20, D90): 4 XLR inputs (analog or AES3), link outputs, NL4 per channel. */
const tourAmp = (hp8: boolean, netLabel = 'Ethernet OCA') => [
  ...ins(4, 'Entrée analog/AES'),
  ...series('thru', 'Link', 4, 'xlr3', A, 'out'),
  ...pair('net', netLabel, 'ethercon', NET),
  ...series('hp', 'Sortie HP', 4, 'speakon', HP, 'out'),
  ...(hp8 ? [port('hp8', 'Sortie NL8 (1-4)', 'speakon8', HP, 'out')] : []),
  pc32(),
]

