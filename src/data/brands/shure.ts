const poe = (label = 'Dante / PoE') => port('net', label, 'rj45', NET, 'io')
const xlrJack = (): Port[] => [port('out', 'Sortie XLR', 'xlr3', A, 'out'), port('outJ', 'Sortie jack', 'jack', A, 'out')]

