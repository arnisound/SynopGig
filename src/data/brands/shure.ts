/* Shure: indicative connectors, check the manufacturer's data sheet. */

const S = 'Shure'
/** Wired mic with a single XLR output. */
const mic = (id: string, model: string, kg: number, phantom = false) =>
  dev(id, S, model, 'Son', { kg }, [port('out', phantom ? 'Sortie (48 V)' : 'Sortie', 'xlr3', A, 'out')])
/** Lavalier / headset terminated on TA4F (for bodypacks). */
const ta4 = (id: string, model: string, kg = 0.02) => dev(id, S, model, 'Son', { kg }, [port('out', 'Sortie (TA4F)', 'mini-xlr', A, 'out')])
/** Handheld wireless transmitter (integrated antenna). */
const handheld = (id: string, model: string, kg = 0.3) => dev(id, S, model, 'Son', { kg }, [port('ant', 'Antenne', 'bnc', RF, 'out')])
/** Bodypack transmitter with TA4F mic/instrument input. */
const bodypack = (id: string, model: string, kg = 0.1) =>
  dev(id, S, model, 'Son', { kg }, [port('mic', 'Entrée micro/instrument (TA4F)', 'mini-xlr', A, 'in'), port('ant', 'Antenne', 'bnc', RF, 'out')])
/** Plug-on transmitter (XLR female input). */
const plugOn = (id: string, model: string, kg = 0.2) =>
  dev(id, S, model, 'Son', { kg }, [port('mic', 'Entrée XLR', 'xlr3', A, 'in'), port('ant', 'Antenne', 'bnc', RF, 'out')])
/** In-ear bodypack receiver. */
const iemPack = (id: string, model: string, kg = 0.2) =>
  dev(id, S, model, 'Son', { kg }, [port('ant', 'Antenne', 'bnc', RF, 'in'), port('hp', 'Écouteurs', 'minijack', A, 'out')])
const earphones = (id: string, model: string) => dev(id, S, model, 'Son', { kg: 0.03 }, [port('in', 'Entrée', 'minijack', A, 'in')])
/** Dante primary / secondary on RJ45. */
